const ATTRS = ['aria-label', 'title', 'placeholder', 'data-dica'];
const originals = new WeakMap();
let idioma = 'pt-BR';
let observador = null;

function traduzir(texto) {
  if (idioma !== 'en-US') return texto;
  const limpo = String(texto).replace(/\s+/g, ' ').trim();
  if (!limpo) return texto;
  let traduzido = EN[limpo];
  if (!traduzido) {
    let m = limpo.match(/^Buscar (.+)$/);
    if (m) traduzido = `Search ${m[1]}`;
    m = limpo.match(/^Nenhum(a)? (.+) ainda$/);
    if (!traduzido && m) traduzido = `No ${m[2]} yet`;
    m = limpo.match(/^A versão (.+) foi baixada e será instalada ao reiniciar\.$/);
    if (!traduzido && m) traduzido = `Version ${m[1]} was downloaded and will be installed on restart.`;
    m = limpo.match(/^A versão (.+) está disponível para baixar\.$/);
    if (!traduzido && m) traduzido = `Version ${m[1]} is available to download.`;
    m = limpo.match(/^Baixando a versão (.+)$/);
    if (!traduzido && m) traduzido = `Downloading version ${m[1]}`;
    m = limpo.match(/^Jogou (.+)$/);
    if (!traduzido && m) traduzido = `Played ${m[1]}`;
    m = limpo.match(/^Buscar (.+)\.\.\.$/);
    if (!traduzido && m) traduzido = `Search ${m[1]}...`;
    m = limpo.match(/^Conta offline "(.+)" criada\.$/);
    if (!traduzido && m) traduzido = `Offline account "${m[1]}" created.`;
    m = limpo.match(/^Conta "(.+)" removida\.$/);
    if (!traduzido && m) traduzido = `Account "${m[1]}" removed.`;
    m = limpo.match(/^Bem-vindo, (.+)!$/);
    if (!traduzido && m) traduzido = `Welcome, ${m[1]}!`;
    m = limpo.match(/^Só as que servem em (.+)$/);
    if (!traduzido && m) traduzido = `Only compatible with ${m[1]}`;
    m = limpo.match(/^Filtrar por (.+)$/);
    if (!traduzido && m) traduzido = `Filter by ${m[1]}`;
    m = limpo.match(/^Nenhum (.+) combina com "(.+)"\.$/);
    if (!traduzido && m) traduzido = `No ${m[1]} match "${m[2]}".`;
    m = limpo.match(/^Modpack do Modrinth(?:: (.+))?$/);
    if (!traduzido && m) traduzido = `Modrinth modpack${m[1] ? `: ${m[1]}` : ''}`;
    m = limpo.match(/^Skin de (.+)$/);
    if (!traduzido && m) traduzido = `Skin for ${m[1]}`;
    m = limpo.match(/^Atualizado em (.+)$/);
    if (!traduzido && m) traduzido = `Updated ${m[1]}`;
    m = limpo.match(/^Baixando (.+) \((\d+)%\)\.\.\.$/);
    if (!traduzido && m) traduzido = `Downloading ${m[1]} (${m[2]}%)...`;
  }
  if (!traduzido) return texto;
  const inicio = String(texto).match(/^\s*/)[0];
  const fim = String(texto).match(/\s*$/)[0];
  return `${inicio}${traduzido}${fim}`;
}

function traduzirTexto(no) {
  if (!no || no.nodeType !== Node.TEXT_NODE) return;
  const pai = no.parentElement;
  if (pai && pai.closest('script,style,pre,code,.log-texto,.conteudo-projeto')) return;
  let origem = originals.get(no);
  const atual = no.nodeValue;
  if (origem === undefined || atual !== traduzir(origem)) {
    origem = atual;
    originals.set(no, origem);
  }
  const novo = traduzir(origem);
  if (atual !== novo) no.nodeValue = novo;
}

function traduzirElemento(el) {
  if (!(el instanceof Element)) return;
  let dados = originals.get(el);
  for (const attr of ATTRS) {
    if (!el.hasAttribute(attr)) continue;
    if (!dados) { dados = new Map(); originals.set(el, dados); }
    const atual = el.getAttribute(attr);
    let origem = dados.get(attr);
    if (origem === undefined || atual !== traduzir(origem)) { origem = atual; dados.set(attr, origem); }
    const novo = traduzir(origem);
    if (atual !== novo) el.setAttribute(attr, novo);
  }
}

function traduzirArvore(no) {
  if (!no) return;
  if (no.nodeType === Node.TEXT_NODE) return traduzirTexto(no);
  if (no.nodeType !== Node.ELEMENT_NODE && no !== document.body) return;
  traduzirElemento(no);
  no.childNodes && no.childNodes.forEach(traduzirArvore);
}

export function aplicarIdioma(novo) {
  idioma = novo === 'en-US' ? 'en-US' : 'pt-BR';
  document.documentElement.lang = idioma;
  try { localStorage.setItem('jg-idioma', idioma); } catch {}
  if (!observador && document.body) {
    observador = new MutationObserver((mutacoes) => {
      for (const m of mutacoes) {
        if (m.type === 'characterData') traduzirTexto(m.target);
        else if (m.type === 'attributes') traduzirElemento(m.target);
        else m.addedNodes.forEach(traduzirArvore);
      }
    });
    observador.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  }
  if (document.body) traduzirArvore(document.body);
}

